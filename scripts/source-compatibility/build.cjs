const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');

const output = path.resolve(__dirname, '../../app/src/main/assets/source-compatibility');
fs.mkdirSync(output, { recursive: true });
const packages = new Set();

function bundle(file, contents) {
  const result = esbuild.buildSync({
    absWorkingDir: __dirname,
    stdin: { contents, resolveDir: __dirname },
    outfile: path.join(output, file),
    bundle: true,
    minify: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2020',
    banner: { js: '// Generated by scripts/source-compatibility/build.cjs.' },
    legalComments: 'inline',
    metafile: true
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    if (!input.startsWith('node_modules/')) continue;
    const packagePath = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)(?:\/|$)/)?.[1];
    if (packagePath) packages.add(packagePath);
  }
}

bundle('crypto.js', `globalThis.__meiloxCryptoJs = require('crypto-js');`);
bundle('musicfree-modules.js', `
  const { URL, URLSearchParams } = require('whatwg-url');
  globalThis.URL ??= URL;
  globalThis.URLSearchParams ??= URLSearchParams;
  globalThis.__meiloxMusicFreeModules = Object.freeze({
    'big-integer': require('big-integer'),
    cheerio: require('cheerio'),
    dayjs: require('dayjs'),
    he: require('he'),
    qs: require('qs')
  });
`);

const notices = new Map();
for (const directory of [...packages].sort()) {
  const base = path.join(__dirname, directory);
  const info = JSON.parse(fs.readFileSync(path.join(base, 'package.json'), 'utf8'));
  const files = fs.readdirSync(base).filter(name => /^(?:licen[sc]e|copying|notice)(?:[-.]|$)/i.test(name)).sort()
    .map(name => path.join(base, name));
  if (info.name === 'boolbase' && info.version === '1.0.0') files.push(path.join(__dirname, 'boolbase-LICENSE'));
  if (!files.length) throw new Error(`Missing license for ${info.name}`);
  notices.set(`${info.name}@${info.version}`, `(${info.license})\n`
    + files.map(name => fs.readFileSync(name, 'utf8')
      .replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trim()).join('\n\n'));
}
const heading = 'Third-party JavaScript used by the isolated source compatibility engine.\n'
  + 'Rebuild with npm ci && npm run build in scripts/source-compatibility.\n';
const entries = [...notices.keys()].sort().map(name => `${name} ${notices.get(name)}`);
fs.writeFileSync(path.join(output, 'THIRD_PARTY_NOTICES.txt'), `${heading}\n${entries.join('\n\n')}\n`);
